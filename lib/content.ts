/** col/row — размер ячейки в bento-сетке «Почему» (6 колонок), как в макете. */
export type Trigger = {
  n: string;
  text: string;
  /**
   * На какую услугу ведёт карточка: клик раскрывает её в разделе «Услуги».
   * Подпись с названием услуги на сайте не выводим — заказчик просил убрать.
   */
  service: ServiceSlug;
  col: 2 | 3 | 6;
  row: 1 | 2;
};
/** Тариф внутри услуги (подготовка к ГИТ — три опции). */
export type ServiceTier = { name: string; includes: string; price: string; term: string };

export type ServiceItem = {
  /** Латинский идентификатор: якорь #service-<slug> и адрес для карточек «Почему». */
  slug: ServiceSlug;
  name: string;
  price: string;
  /** Подробности из брифа (docs/client-brief.md, разделы 3–11); без них
   *  строка не раскрывается — так у SaaS-платформы. */
  details?: {
    text: string;
    term?: string;
    includes?: string[];
    steps?: string[];
    gives: string[];
    tiers?: ServiceTier[];
  };
};
export type ServiceGroup = {
  n: string;
  title: string;
  /** «Для компаний, которым…» — кому адресована группа. */
  audience: string;
  count: string;
  items: ServiceItem[];
};
/** art — какой арт-вырезке соответствует шаг; не совпадает с номером после правок. */
export type Step = { n: string; art: string; text: string };

